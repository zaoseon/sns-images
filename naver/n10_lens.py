def put(body, sec, label, lines):
    if lines[0] in body: return body, 0
    m = re.search(rf"<p>&nbsp;</p><p><b>{sec}\.", body)
    if not m: raise SystemExit(f"{sec}번 소제목 앞자리 못 찾음")
    blk = "<p>&nbsp;</p>" + f"<p>{label}</p>" + "".join(f"<p>{html.escape(s, quote=False)}</p>" for s in lines)
    return body[:m.start()] + blk + body[m.start():], 1
