def v2_names(pid):
    sp = V2.plan()[pid]; return [f"naver_z{sp['key']}_{k.lower()}6" for k in sp["diag"]]


def drop(body, part):
    pat = re.compile(r'<p><img[^>]*src="[^"]*' + re.escape(part) + r'[^"]*"[^>]*></p>(?:<p>&nbsp;</p>)?')
    body, k = pat.subn("", body); assert k == 1, (part, k); return body


def run(only=None):
    P = plan(); pages = json.load(open(PG, encoding="utf-8")); made = []
    for pid, sp in P.items():
        if only and pid not in only: continue
        c = V2.pal(pid); key = sp["key"]
        r, cc = sp["R"], sp["C"]
        if len(r) == 4: rs, rletter, rfn, ralt, rtxt = None, r[0], r[1], r[2], r[3]
        else: rs, rletter, rfn, ralt, rtxt = r
        cs, cletter, cfn, calt, ctxt = cc
        rn, cn = f"naver_z{key}_{rletter}7.jpg", f"naver_z{key}_{cletter}7.jpg"
        for n, fn in ((rn, rfn), (cn, cfn)):
            if B.PREVIEW or not B1.have(n): fn(n, c)
            made.append(n)
        if B.PREVIEW: continue
        body = pages[pid]["body"]
        if "3판" in pages[pid].get("k131", ""): print("이미 3판:", pid); continue
        # 2판 그림을 떼어 낸다(심리 단락 자리 그림은 앞 줄과 함께 정리)
        slot = None
        for part in v2_names(pid):
            m = re.search(re.escape(LEAD) + r'<p><img[^>]*src="[^"]*' + re.escape(part) + r'[^"]*"[^>]*></p>', body)
            if m: slot = part; body = body[:m.start()] + "%%SLOT%%" + body[m.end():]
            else: body = drop(body, part)
        assert slot, pid
        if rs is None: body = body.replace("%%SLOT%%", P_(rtxt) + B1.IMG(rn, ralt).replace(B1.BL, ""))
        else:
            body = body.replace("%%SLOT%%" + B1.BL, "").replace("%%SLOT%%", "")
            body = B1.after_head(body, rs, P_(rtxt) + B1.IMG(rn, ralt))
        body = B1.after_head(body, cs, P_(ctxt) + B1.IMG(cn, calt))
        assert "%%SLOT%%" not in body
        pages[pid]["body"] = body; pages[pid]["k131"] = TAG
    if not B.PREVIEW:
        open(PG, "w", encoding="utf-8").write(json.dumps(pages, ensure_ascii=False, indent=1) + "\n")
    return made


