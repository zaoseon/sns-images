def strip_img(body, part):
    pat = re.compile(r'<p><img[^>]*src="[^"]*' + re.escape(part) + r'[^"]*"[^>]*></p>(?:<p>&nbsp;</p>)?')
    body, k = pat.subn("", body); assert k == 1, (part, k); return body

