def heads(body):
    t = [html.unescape(re.sub(r"<[^>]+>", "", x)).strip() for x in re.findall(r"<p><b>(\d\. [^<]+)</b></p>", body)]
    out = []
    for x in t:
        x = re.sub(r"^\d\. ", "", x)
        if x in out or "해 볼 것" in x or "자주 묻는" in x: continue
        out.append(x)
    return out[:4]


def run(only=None):
    pages = json.load(open(PG, encoding="utf-8")); ic = json.load(open(IC, encoding="utf-8")); done = []
    for pid, (kw, intent, new, keys, imgs) in C.items():
        if only and pid not in only: continue
        v = pages[pid]; body = v["body"]
        if pid in ic["cards"] and ic["cards"][pid].get("applied"): print("이미 반영:", pid); continue
        i = body.index("<p>안녕하세요"); old = body[:i]
        assert old.count("<p>") >= 2 and len(old) < 600, (pid, "도입부 모양")
        f3 = html.unescape(re.sub(r"<[^>]+>", " ", new))
        assert all(k in f3 for k in keys), (pid, "답 낱말")
        v["body"] = new + body[i:]
        ic["cards"][pid] = {"keywords": kw, "keyword_src": SRC, "intent": intent,
                            "first3": re.sub(r"\s+", " ", f3).strip(), "answer_keys": keys,
                            "order": heads(body), "images": imgs, "related": (v.get("related") or {}).get("id"),
                            "cta": pid, "experience": [], "applied": True, "src": "① 10/20 19:45 intent_apply_1020b"}
        done.append(pid)
    open(PG, "w", encoding="utf-8").write(json.dumps(pages, ensure_ascii=False, indent=1) + "\n")
    json.dump(ic, open(IC, "w", encoding="utf-8"), ensure_ascii=False, indent=1); open(IC, "a").write("\n")
    return done


