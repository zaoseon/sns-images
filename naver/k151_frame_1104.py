def heads(b, pairs, toc=True):
    """번호 소제목과 차례 줄을 같이 바꾼다. new 가 None 이면 그 소제목을 지우고(차례에서도), new 가 '<b>'로 시작하면 번호 없는 작은 제목으로."""
    for old, new in pairs:
        b = rep(b, f"<p><b>{old}</b></p>", new if (new or "").startswith("<p>") else f"<p><b>{new}</b></p>")
        if toc:
            tnew = None if (new or "").startswith("<p>") else new
            b = rep(b, f"<p>{old}</p>", f"<p>{tnew}</p>" if tnew else "")
    return b

def months(b, fmt, marks=None):
    """달 머리줄 꼴을 글마다 다르게. 날짜·간지는 그대로."""
    rx = re.compile(r"(🔹|🔸) <b>((?:이듬해 )?(\d+)월)\(((\d+)월 (\d+)일) 무렵부터\)</b>: ([^<]+?)의 달이에요\.")
    n = len(rx.findall(b)); assert n == 5, n
    def one(m):
        mk = (marks or {}).get(m.group(1), m.group(1)); ih = "이듬해 " if m.group(2).startswith("이듬해") else ""
        return fmt.format(mk=mk, month=m.group(2), date=ih + m.group(4), animal=m.group(7))
    return rx.sub(one, b)

