    (_, _, _, _, _, _, title, hero2, scene, summary, saju, star, num, count_note, same, diff, actions, faq, tags, trow, arow) = a[:21]
    fx = lambda ls: [l.replace("이 부분은 선택의 영역이에요.", nw["choose"]).replace("다른 말도 있어요.", nw["other"]) for l in ls]
    extra = kw.get("extra") or ""; pre = f"naver_z{no:02d}"; hd = nw["heads"]; mi = nw["mi"]
    def withintro(blk, intro): return P(blk[0], *([intro] if intro else []), *blk[1:])
    if r["cc"]: cnt_lines = list(r["cc"][1])
    else:
        c3, c1, c0 = nw["cnt"]
        cnt_lines = [nw["countline"], "🔹 <b>3개</b>: " + c3, "🔹 <b>2개</b>: " + count_note, "🔹 <b>1개</b>: " + c1, "🔹 <b>0개</b>: " + c0]
    body = (P(scene, nw["greet"]) + IMG(f"{pre}_a.jpg") + P(nw["lead"]) + P(*summary) +
            P("<b>📌 이 글의 순서</b>", *hd) +
            H(hd[0]) + P(nw["intro"]) +
            H(hd[1]) + IMG(f"{pre}_b.jpg") + withintro(saju, mi["saju"]) + withintro(star, mi["star"]) + withintro(num, mi["num"]) + (extra or "") + P(nw["sell"]) +
            H(hd[2]) + P(*cnt_lines) +
            H(hd[3]) + P(*fx(same)) + P(*fx(diff)) +
            H(hd[4]) + IMG(f"{pre}_c.jpg") + P(*actions) +
            H(hd[5]) + "".join(P(f"<b>Q. {q}</b>", f"A. {a_}") for q, a_ in faq) +
            P(nw["cta"]) + END + P(nw["close"]) + SEAL)
    # 연결 문구(👇)는 MP.add(related=...)가 본문 끝에 자동으로 붙인다 - 여기서 또 붙이면 두 번 들어간다(10/3 점검에서 발견)
    for bad in ("—", "엔진", "초안"): assert bad not in body, (no, bad)
    return body, dict(no=no, title=title, tags=tags, date=a[1], time=a[2])
