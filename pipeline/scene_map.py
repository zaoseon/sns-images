"""R52 문장 유형 -> 장면 형태 표와 검사 (10/11, 릴스공장 스킬팩 캐러셀 분석에서 가져옴).
정보형 릴스·클립을 기획할 때 문장마다 유형을 적고, 그 유형에 맞는 장면 형태를 고른다. 같은 형태가 연달아 나오면 걸린다(R19)."""
# 문장 유형 -> 쓸 수 있는 장면 형태(R19 형태 이름 + 실제 화면). 앞의 것이 기본값
MAP = {
    "용어·키워드": ["키네틱 글자", "큰 글자 한 줄"],
    "숫자·비율": ["큰 숫자 세기", "점 격자", "막대", "겹치는 두 원", "게이지"],
    "비교": ["좌우 비교 패널", "겹치는 두 원", "막대"],
    "기능·결과 보여 주기": ["실제 화면", "카드 뒤집기"],
    "순서·과정": ["노선도", "체크 목록", "여섯 방향 칸"],
    "분류·여러 개": ["여섯 방향 칸", "12궁·60괘 판", "오행 그림"],
    "정리·마무리": ["체크 목록", "한 줄 정리"],
}
FORMS = sorted({f for v in MAP.values() for f in v})

def lint(scenes):
    """scenes: [(문장 유형, 장면 형태), ...] 순서대로. 문제 목록(문장)을 돌려준다. 빈 목록이면 통과."""
    out = []
    for i, (t, f) in enumerate(scenes):
        if t not in MAP:
            out.append("%d번 장면: 모르는 문장 유형 '%s'" % (i + 1, t)); continue
        if f not in MAP[t]:
            out.append("%d번 장면: '%s' 문장에 '%s'은(는) 맞지 않아요(쓸 수 있는 것: %s)" % (i + 1, t, f, ", ".join(MAP[t])))
        if i and scenes[i - 1][1] == f:
            out.append("%d번 장면: 앞 장면과 같은 형태 '%s'가 연달아 나와요(R19)" % (i + 1, f))
    return out
