"""글(카피·훅) 규칙 한 곳 — 대표 10/16 "카피나 훅, 표현 규칙도 정리 좀 하자".

그림 규격은 `channel_specs`·`brand_frame`·`card_gate` 가 맡는다. 여기는 **글**만 맡는다.

왜 만들었나
  훅 목록이 `naver/prep_post.py` 안에만 파이썬 리스트로 있었다. 그래서 카드·릴스 쪽에서는
  훅 유형을 **적었는지만** 보고 **값이 목록 안인지 대조하지 못했다**(card_gate 의 빈 칸 검사).
  금지어도 파일 일곱 군데에 조금씩 다르게 흩어져 있었다.

여기서 정하는 것
  훅()      훅 열한 가지(K-064). 26가지는 바깥 조사 자료이지 우리 목록이 아니다
  첫줄검사() 첫 줄(훅)에 체계 이름을 넣지 않는다 — K-102
  해시태그() 채널마다 개수가 다르다 — 인스타 5 · 스레드 1 · 네이버 클립 5
  금지어     여러 파일의 합집합. 쓰는 쪽이 골라 쓴다

K-102 의 근거 (10/16 우리 릴스 28편 실측, content/audit/reel_metrics.json)
  첫 줄에 체계 이름이 있으면 3초율 5.9%(10편), 없으면 9.6%(18편).
  형식(일간 성격)을 빼고 봐도 4.5%(6편) 대 8.1%(15편) — 1.8배가 그대로 남는다. 두 번 확인됐다.
"""
import re

# ── 훅 열한 가지 (K-064). 네이버·카드·릴스가 같은 목록을 쓴다 ────────────────
훅 = ("자가진단·번호 고르기", "사람들이 실제로 치는 질문 인용", "상황 지목",
      "계산 내역 공개", "맞대결(같은 말·다른 말)", "허락",
      "마음 공감(저만 그런가요)", "작은 행동 큰 결과", "빠른 이해(1분이면)",
      "번호형 해결책", "흔한 오해 교정")

# 바깥 조사에서 본 26가지 중 쓰지 않기로 판정한 갈래(docs/훅26가지_해외릴스_판정_2026-10-16.md).
# 이름이 아니라 '성격'으로 적는다 — 번호로 부르면 두 판정표의 번호가 서로 달라 헷갈린다.
안쓰는훅 = ("성과 자랑", "공포·협박", "가짜 통계", "조급함 몰기", "남 깎아내리기")

# ── 첫 줄(훅)에 넣지 않는 말 — K-102 ──────────────────────────────────────
체계이름 = re.compile(r"자미두수|하락이수|수비학|육효|당사주|교차분석|운명학|점성술")
# '사주'와 '별자리'는 사람들이 아는 말이라 막지 않는다. 다만 첫 줄이 **그 둘의 관계를 묻는** 꼴이면 막는다
# ("내 사주와 별자리는 같은 말을 할까요?" — 우리 체계 설명이지 보는 사람 이야기가 아니다).
체계관계 = re.compile(r"(사주|별자리)\s*(와|과|랑|하고)\s*\S*\s*(같은|다른|닮|통|맞)")

# ── 채널마다 다른 해시태그 개수 ───────────────────────────────────────────
해시태그수 = {"insta": 5, "threads": 1, "naver_clip": 5}

# ── 금지어 (여러 파일의 합집합, 10/16 정리) ───────────────────────────────
확신 = ("반드시", "무조건", "확실합니다", "적중률", "적중", "100%")
내부말 = ("엔진", "초안", "의미축", "환산", "교차 시험", "기궁", "흉성", "6체계", "리포트", "데이터 릴스", "수린")
옛표현 = ("타고난 결", "세 지도", "두 지도", "세 가지 지도", "겹으로")
불안 = ("큰일", "손해", "치료")
금지어 = 확신 + 내부말 + 옛표현 + 불안


def 첫줄검사(줄):
    """릴스·카드의 첫 줄(훅)을 본다. 걸리는 까닭 목록을 돌려준다(비면 통과)."""
    bad = []
    if 체계이름.search(줄):
        bad.append(f"첫 줄에 체계 이름이 있어요: '{체계이름.search(줄).group()}'. "
                   "보는 사람이 모르는 말이라 멈추지 않아요(K-102 — 28편 실측 1.8배 차이). "
                   "아는 말로 바꾸세요(타고난 성격·속마음·올해 흐름).")
    if 체계관계.search(줄):
        bad.append("첫 줄이 '우리 체계 둘이 서로 맞느냐'를 묻고 있어요. "
                   "보는 사람 이야기로 바꾸세요(K-102).")
    for w in 금지어:
        if w in 줄:
            bad.append(f"금지어 '{w}'")
    return bad


# 같은 훅을 두 이름으로 부르고 있었다 — K-064 목록과 26가지 판정표(docs/훅26가지…)의 이름이 다르다.
# 10/16에 사양을 세어 보니 두 이름이 섞여 쓰이고 있었다. 뜻이 같은 것끼리 묶어 둔다.
별칭 = {"감정 공감형": "마음 공감(저만 그런가요)",
        "오해 교정": "흔한 오해 교정",
        "자가진단": "자가진단·번호 고르기",
        "숫자 공개": "계산 내역 공개",
        "따라 하기 안내": "빠른 이해(1분이면)",
        "상황 지목형": "상황 지목"}


def 바른이름(유형):
    """사양에 적은 이름을 K-064 의 이름으로 바꾼다. 꼬리말(설명)은 떼고 본다."""
    if not 유형:
        return None
    t = str(유형).split("(")[0].strip() if str(유형).split("(")[0].strip() in 별칭 else str(유형).strip()
    for k, v in 별칭.items():            # "오해 교정(#15 …)" 처럼 설명이 붙은 것도 받는다
        if t == k or t.startswith(k + "("):
            return v
    return t


def 훅검사(유형):
    """사양에 적은 훅 유형이 열한 가지 안인지 본다. card_gate 가 부른다."""
    if not 유형:
        return ["훅 유형을 사양에 적으세요(K-064 열한 가지 중 하나). 안 적으면 같은 유형만 쓰게 돼요."]
    이름 = 바른이름(유형)
    if 이름 in 훅:
        return []
    가까운 = [h for h in 훅 if str(이름).split("·")[0][:3] in h]
    귀띔 = f" 혹시 이것인가요: {가까운[0]}" if 가까운 else ""
    return [f"훅 유형 '{유형}' 은 열한 가지에 없어요(K-064).{귀띔}\n"
            f"    쓸 수 있는 것: {' · '.join(훅)}"]


def 태그검사(태그목록, 채널="insta"):
    """채널에 맞는 해시태그 개수인지. 스레드는 1개다 — 인스타 5개를 그대로 쓰면 안 된다."""
    want = 해시태그수.get(채널, 5)
    if len(태그목록) != want:
        return [f"{채널} 해시태그는 {want}개인데 {len(태그목록)}개예요."]
    if 채널 in ("insta", "naver_clip") and "#사주" not in 태그목록:
        return ["첫 태그에 #사주 가 있어야 해요."]
    return []
