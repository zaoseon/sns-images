"""인스타 릴스 안전 영역 (10/3 대표: 릴스가 피드에서 위가 다 잘려 보임). 출처: 인스타 사이즈 가이드 여러 건(2026), 공식 문서는 못 찾음.
릴스 1080x1920은 보는 곳에 따라 다르게 잘린다: 릴스 탭=전체(위 약 250·아래 약 450·오른쪽 약 120은 앱 버튼·계정명·캡션에 가림), 피드=가운데 4:5(y 285~1635), 프로필 격자=3:4(y 240~1680),
첫 화면(표지)의 핵심은 가운데 1:1(y 420~1500). 그래서 글자·배지·얼굴·AI 표시는 모두 아래 사각형 안에 둔다. 배경 그림은 화면 전체를 채워도 된다."""
W, H = 1080, 1920
TOP, BOTTOM = 330, 1470        # 피드 4:5(285~1635)와 릴스 탭 앱 버튼(위 250·아래 450 가림)의 교집합에 여유를 더함
LEFT, RIGHT = 50, 960          # 오른쪽은 좋아요·댓글·공유 버튼(약 120px)을 피한다
COVER_TOP, COVER_BOTTOM = 420, 1500   # 첫 화면 핵심(제목)은 가운데 1:1 안에
def inside(box, cover=False):
    x0, y0, x1, y1 = box; t, b = (COVER_TOP, COVER_BOTTOM) if cover else (TOP, BOTTOM)
    return x0 >= LEFT and x1 <= RIGHT + 40 and y0 >= t and y1 <= b
