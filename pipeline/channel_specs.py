def export(path):
    """모든 채널 규격을 JSON 한 파일로(다른 도구·GPT·편집기가 같은 값을 읽게). 이 파일은 만들어지는 것이다 — 고치지 말고 여기를 고친다."""
    import json
    out = {"_설명": "channel_specs.py 에서 만든 채널 템플릿(자동 생성). 좌표 [x0,y0,x1,y1] px. deadzone 종류 ui=UI가 덮음 / band=여백·띠(고정 요소만) / caution=잘리거나 덮일 수 있음",
           "balance": BALANCE, "gap": GAP, "channels": {}}
    for k, d in CH.items():
        out["channels"][k] = dict(name=d["name"], w=d["w"], h=d["h"], h_free=d.get("h_free", False), safe=list(d["safe"]), align=d.get("align", "center"),
                                  zones=[dict(name=z[0], box=list(z[1:5]), note=z[5] if len(z) > 5 else "") for z in d.get("zones", [])],
                                  deadzone=[dict(kind=a, box=list(b), note=c) for a, b, c in d.get("deadzone", [])],
                                  min_text=d.get("min_text", BALANCE["min_text"]), fonts=d.get("fonts", {}), source=d.get("conf", ""))
    json.dump(out, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return path


def dz_check(name):
    """안전 영역·구역이 데드존(ui)과 겹치지 않는지 잰다. 고정 줄은 band 안에 있어도 된다."""
    d = CH[name]; bad = []
    for kind, (a, b, c, e), why in d.get("deadzone", []):
        if kind != "ui": continue
        for z in d["zones"]:
            x0, y0, x1, y1 = z[1:5]
            if x0 < c and x1 > a and y0 < e and y1 > b:
                bad.append(f"{name} '{z[0]}' ({x0},{y0},{x1},{y1}) 가 데드존 '{why}' ({a},{b},{c},{e}) 와 겹쳐요.")
    return bad


