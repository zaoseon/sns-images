def check(name=None):
    """구역표가 서로 어긋나지 않는지 잰다. 어긋난 곳 목록을 돌려준다(빈 목록이면 이상 없음).
    10/16: 릴스 '상단 라벨' 이 상단 고정 줄과 같은 y(340)라 배지가 '자오선' 워드마크를 덮고 있었는데,
    규격을 재 보는 곳이 없어서 빌더마다 따로 땜질하고 있었다."""
    bad = []
    for n in ([name] if name else CH):
        d = CH[n]; Z = {z[0]: z[1:5] for z in d.get("zones", [])}
        sx0, sy0, sx1, sy1 = d["safe"]
        for 이름, (x0, y0, x1, y1) in Z.items():
            if "고정" in 이름 or "글자 금지" in (dict((z[0], z[5]) for z in d["zones"]).get(이름, "")):
                continue
            if y0 < sy0 or y1 > sy1 or x0 < sx0 or x1 > sx1:
                bad.append(f"{n} '{이름}' ({x0},{y0},{x1},{y1}) 가 안전 영역 {d['safe']} 밖이에요.")
        위 = max((Z[k][3] for k in Z if k.startswith("상단") and "고정" in k), default=None)
        lab = Z.get("상단 라벨")
        if 위 is not None and lab and lab[1] - 위 < GAP:
            bad.append(f"{n} 배지가 상단 고정 줄과 {lab[1]-위}px 밖에 안 떨어졌어요({GAP}px 이상). "
                       f"배지 글자가 '자오선' 워드마크를 덮습니다.")
        순서 = [k for k in ("상단 라벨", "제목", "본문·그림", "본문·선택지", "버튼·마무리") if k in Z]
        for a, b in zip(순서, 순서[1:]):
            if Z[b][1] < Z[a][3]:
                bad.append(f"{n} '{a}'({Z[a][3]}) 와 '{b}'({Z[b][1]}) 구역이 겹쳐요.")
    return bad


